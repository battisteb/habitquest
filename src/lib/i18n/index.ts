export type Strings = Record<keyof typeof FR, string>;

const STRINGS: Record<Lang, Strings> = { fr: FR, en: EN, ja: JA };

/** Both dictionaries, for tests only. */
export const STRINGS_FOR_TESTS = STRINGS;

/** Reactive hook — re-renders when language changes */
/** Current app language (reactive). */
export function useLang(): Lang {
  return use$(lang$);
}

export function useT(): Strings {
  const lang = use$(lang$);
  return STRINGS[lang];
}

/** Current texts outside React (stores, services); not reactive. */
export function getStrings(): Strings {
  return STRINGS[lang$.get()];
}
